def semantic_instructions(original):
    mode = os.getenv("EDITOR_SEARCH_RUBRIC", "legacy")
    if mode == "legacy":
        return original
    if mode == "local_skill":
        host = urlsplit(search_endpoint("semantic").base).hostname
        if host not in {"localhost", "127.0.0.1", "::1"}:
            raise ValueError("Полная локальная рубрика доступна через локальный модельный endpoint.")
        path = os.getenv("EDITOR_RUBRIC_PATH")
        if not path or not Path(path).is_file():
            raise ValueError("Укажите файл локальной рубрики в EDITOR_RUBRIC_PATH.")
        return Path(path).read_text()
    if mode == "reader_task":
        return READER_TASK
    raise ValueError("Неизвестная рубрика поиска")


def search_endpoint(channel):
    # Slopotron remains a separate channel with an independently configurable model.
    return Endpoint.role("SEARCH" if channel == "semantic" else "SLOPOTRON")
